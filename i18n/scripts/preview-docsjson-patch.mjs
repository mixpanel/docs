#!/usr/bin/env node
/**
 * preview-docsjson-patch.mjs — show (and stage) the docs.json edit that enables i18n,
 * WITHOUT modifying docs.json.
 *
 * Enabling Mintlify i18n is a one-shape change: `navigation.tabs` becomes
 * `navigation.languages[]`, with the existing tree as the `en` entry and each other locale
 * `$ref`'d out to its own file — the layout Mintlify uses for their own docs.
 *
 * Usage:
 *   node i18n/scripts/preview-docsjson-patch.mjs ko            # print the change
 *   node i18n/scripts/preview-docsjson-patch.mjs ko --write    # also write i18n/nav/docs.json.preview
 *
 * Applying it is a deliberate, human step — see i18n/nav/README.md.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const locale = process.argv[2] || "ko";
const write = process.argv.includes("--write");

const raw = readFileSync(resolve(ROOT, "docs.json"), "utf8");
const docs = JSON.parse(raw);
const nav = docs.navigation;

if (nav.languages) {
  console.log("docs.json already uses navigation.languages — nothing to preview.");
  process.exit(0);
}
if (!nav.tabs) {
  console.error("Unexpected docs.json: navigation has neither `tabs` nor `languages`.");
  process.exit(1);
}

const patched = structuredClone(docs);
patched.navigation = {
  languages: [{ language: "en", tabs: nav.tabs }, { $ref: `./${locale}.json` }],
  ...(nav.global ? { global: nav.global } : {}),
};

const tabNames = nav.tabs.map((t) => t.tab).join(", ");
console.log(`
docs.json change — navigation.tabs → navigation.languages

  BEFORE                              AFTER
  "navigation": {                     "navigation": {
    "tabs": [ ... ],        ──▶         "languages": [
    "global": { ... }                     { "language": "en", "tabs": [ ...unchanged... ] },
  }                                       { "$ref": "./${locale}.json" }
                                        ],
                                        "global": { ... }
                                      }

  • the ${nav.tabs.length} English tabs (${tabNames}) move verbatim under language "en"
  • "en" is first, so it stays the default; English URLs do not change
  • ${locale}.json carries the ${locale} tree (generated by build-locale-nav.mjs)
  • global anchors stay shared across languages — see i18n/nav/README.md
`);

if (write) {
  const out = resolve(ROOT, "i18n/nav/docs.json.preview");
  writeFileSync(out, `${JSON.stringify(patched, null, 2)}\n`);
  console.log(`✓ wrote i18n/nav/docs.json.preview (${(JSON.stringify(patched).length / 1024).toFixed(0)} KB)`);
  console.log("  diff it:  git diff --no-index docs.json i18n/nav/docs.json.preview");
} else {
  console.log("  re-run with --write to stage i18n/nav/docs.json.preview for diffing.");
}
